        public static PlayerTheme Resolve(string? id)
        {
            return All.FirstOrDefault(theme => theme.Id == id)
                ?? All.First(theme => theme.Id == DefaultId);
        }

        private static Color C(int r, int g, int b)
        {
            return Color.FromArgb(r, g, b);
        }

        private static Color A(int r, int g, int b, int a)
        {
            return Color.FromArgb(a, r, g, b);
        }
